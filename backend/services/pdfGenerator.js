const PDFDocument = require('pdfkit');
const fs = require('fs');

class PdfGenerator {
  /**
   * Generates a professional PDF report from the analysis data.
   * @param {Object} project - The populated Project document
   * @param {Object} analysis - The populated Analysis document
   * @param {string} outputPath - The absolute file path to save the PDF
   * @param {string} userName - The name of the user generating the report
   * @returns {Promise<string>}
   */
  generateReport(project, analysis, outputPath, userName) {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 50, size: 'A4' });
        const stream = fs.createWriteStream(outputPath);
        
        doc.pipe(stream);

        const data = analysis.analysis;
        const generatedDate = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

        // --- GLOBAL SETTINGS ---
        const primaryColor = '#2563eb'; // Blue
        const textColor = '#1f2937';    // Dark Gray
        const secondaryText = '#4b5563'; // Medium Gray

        // ==========================================
        // COVER PAGE
        // ==========================================
        doc.moveDown(5);
        doc.fontSize(32).fillColor(primaryColor).text('PatentIQ', { align: 'center' });
        doc.moveDown(1);
        doc.fontSize(24).fillColor(textColor).text('Patent Potential Analysis Report', { align: 'center' });
        
        doc.moveDown(4);
        doc.fontSize(16).fillColor(secondaryText).text('Project Title:', { align: 'center' });
        doc.fontSize(18).fillColor(textColor).text(project.title, { align: 'center' });

        doc.moveDown(4);
        doc.fontSize(12).fillColor(secondaryText).text(`Generated Date: ${generatedDate}`, { align: 'center' });
        doc.text(`Generated By: ${userName || 'User'}`, { align: 'center' });
        doc.text(`Analysis ID: ${analysis._id.toString()}`, { align: 'center' });
        
        // Metadata
        doc.moveDown(1);
        doc.fontSize(10).fillColor(secondaryText).text(`Analysis Model: ${analysis.modelUsed || 'gemini-3.1-flash-lite'}`, { align: 'center' });
        doc.text(`Processing Time: ${analysis.processingTime || 0}ms`, { align: 'center' });
        doc.text(`Supporting Context Chunks: ${analysis.retrievedChunkCount || 0}`, { align: 'center' });

        // ==========================================
        // PAGE 2: SUMMARY & SCORES
        // ==========================================
        doc.addPage();
        
        doc.fontSize(20).fillColor(primaryColor).text('Executive Summary', { underline: true });
        doc.moveDown(0.5);
        doc.fontSize(12).fillColor(textColor).text(data.innovationSummary || 'No summary available.');

        doc.moveDown(1.5);
        doc.fontSize(16).fillColor(primaryColor).text('Technical Domain', { underline: true });
        doc.moveDown(0.5);
        doc.fontSize(12).fillColor(textColor).text(data.technicalDomain || 'Unspecified');

        doc.moveDown(2);
        doc.fontSize(20).fillColor(primaryColor).text('Patentability Scores', { underline: true });
        doc.moveDown(1);
        
        const scores = [
          { label: 'Novelty Score', value: data.noveltyScore || 0 },
          { label: 'Similarity Score', value: data.similarityScore || 0 },
          { label: 'Patent Potential Score', value: data.patentPotentialScore || 0 },
          { label: 'Confidence Score (RAG)', value: data.confidence || 0 },
        ];

        scores.forEach(s => {
          doc.fontSize(14).fillColor(textColor).text(`${s.label}: ${s.value}%`);
          doc.moveDown(0.2);
          
          const barWidth = 300;
          const scoreWidth = (s.value / 100) * barWidth;
          
          doc.rect(doc.x, doc.y, barWidth, 10).fill('#e5e7eb');
          doc.rect(doc.x, doc.y, scoreWidth, 10).fill(primaryColor);
          doc.y += 15;
          doc.moveDown(1);
        });

        // ==========================================
        // PAGE 3: RECOMMENDATION & ANALYSIS
        // ==========================================
        doc.addPage();
        
        doc.fontSize(20).fillColor(primaryColor).text('Final Recommendation', { underline: true });
        doc.moveDown(0.5);
        doc.fontSize(14).fillColor(textColor).text(data.recommendation || 'N/A', { bold: true });

        doc.moveDown(2);
        doc.fontSize(20).fillColor(primaryColor).text('Strengths', { underline: true });
        doc.moveDown(0.5);
        if (data.strengths && data.strengths.length > 0) {
          data.strengths.forEach(pt => {
            doc.fontSize(12).fillColor(textColor).text(`• ${pt}`);
          });
        } else {
          doc.fontSize(12).fillColor(textColor).text('None provided.');
        }

        doc.moveDown(2);
        doc.fontSize(20).fillColor(primaryColor).text('Weaknesses / Risks', { underline: true });
        doc.moveDown(0.5);
        if (data.weaknesses && data.weaknesses.length > 0) {
          data.weaknesses.forEach(pt => {
            doc.fontSize(12).fillColor(textColor).text(`• ${pt}`);
          });
        } else {
          doc.fontSize(12).fillColor(textColor).text('None identified.');
        }

        // ==========================================
        // PAGE 4: COMMERCIAL & CONTEXT
        // ==========================================
        doc.addPage();
        
        doc.fontSize(20).fillColor(primaryColor).text('Commercial Applications', { underline: true });
        doc.moveDown(0.5);
        if (data.commercialApplications && data.commercialApplications.length > 0) {
          data.commercialApplications.forEach(pt => {
            doc.fontSize(12).fillColor(textColor).text(`• ${pt}`);
          });
        } else {
          doc.fontSize(12).fillColor(textColor).text('None identified.');
        }

        doc.moveDown(2);
        doc.fontSize(20).fillColor(primaryColor).text('Supporting Context (Retrieved Patents)', { underline: true });
        doc.moveDown(0.5);
        
        // Remove duplicates just for display
        const uniquePatents = [...new Set(analysis.retrievedPatents || [])];
        if (uniquePatents.length > 0) {
          uniquePatents.forEach(ref => {
            doc.fontSize(12).fillColor(textColor).text(`• Patent ID: ${ref}`);
          });
        } else {
          doc.fontSize(12).fillColor(textColor).text('No supporting context retrieved.');
        }

        doc.end();

        stream.on('finish', () => resolve(outputPath));
        stream.on('error', (err) => reject(err));
      } catch (error) {
        reject(error);
      }
    });
  }
}

module.exports = new PdfGenerator();
